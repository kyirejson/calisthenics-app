// Style guidance only: no output truncation, tool restriction or intent routing.
export function responseStyle(mode = 'text') {
  return `表达要求：先说结论，简洁、干练、自然。不重复用户问题，不堆砌铺垫、客套、步骤复述和无关建议。工具操作成功时直接说明结果；失败时简要说明真实原因和必要的下一步，不把尚未核实的操作说成成功。简单问题简短回答；用户要求详细解释或任务确实复杂时，保留必要信息，不为了简短而省略关键事实。这些要求只影响表达，不减少你对上下文的理解、推理和使用已授权工具的能力。${mode === 'voice' ? '\n当前是语音对话：使用适合直接朗读的短句，避免长清单、Markdown 符号和反复总结；通常用简短口语说明结果，确有必要或用户要求时再展开。唤醒确认“我在”已由本地播放，正常回答不要再补一句唤醒确认。' : '\n当前是文字对话：尽量用紧凑的段落，只有确实有帮助时才分条。'}`;
}
