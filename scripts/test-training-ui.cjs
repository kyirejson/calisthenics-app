  await wait('JSON.parse(localStorage.getItem("sessions")).length === 2', 'checked again');
  await cdp('Page.reload');
  await wait('document.body.innerText.includes("开始完整训练")', 'refresh preserved partial progress');
  const draft = await evaluate('JSON.parse(localStorage.getItem("sessions"))[0]');
  assert.equal(draft.completion, 'partial'); assert.equal(draft.exercises[0].sets.length, 1);
  console.log('PASS live autosave, unchecking retracts draft, refresh preserves checked sets');
  await evaluate(`localStorage.setItem('user_profile',${JSON.stringify(JSON.stringify({ ...profile, experience: 'beginner', frequency: 2 }))})`);
  await cdp('Page.reload');
  await wait('document.body.innerText.includes("初试身手")', 'beginner recovery preview');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  await clickLabel('9月29日 周二');
  await wait('document.body.innerText.includes("屈膝支撑保持")', 'beginner recovery list');
  await clickLabel('查看屈膝支撑保持动作指导');
  await wait('document.body.innerText.includes("按升级标准训练此动作")', 'recovery detail');
  await click('按升级标准训练此动作');
  await wait('document.body.innerText.includes("训练计时")', 'recovery practice');
  await click('动作指导与原文  ›');
  await wait('document.body.innerText.includes("资料原文与配图")', 'recovery detail');
  await click('资料原文与配图');
  await wait('document.body.innerText.includes("第一式 曲腿式")', 'matched original beginner section');
  console.log('PASS beginner recovery preview includes matching original guidance');
  // Saturday in stage IV is an inversion/bridge day; use only this isolated profile.
  const neckProfile = { ...profile, experience: 'elite', frequency: 6, levels: { ...profile.levels, bridge: 6 }, neckBridgeConsent: false };
  await evaluate(`localStorage.setItem('user_profile',${JSON.stringify(JSON.stringify(neckProfile))}); localStorage.setItem('sessions','[]'); localStorage.setItem('daily_workout_edits','{}')`);
  await cdp('Page.reload');
  await wait('document.body.innerText.includes("尚未解锁")', 'compact gate on today screen');
  const compactHome = await evaluate('document.body.innerText');
  for (const removed of ['未来 7 天', '接近维持能量', '单日累计 200 次', '检查颈桥条件']) assert.ok(!compactHome.includes(removed), `${removed} is not on the home surface`);
  await clickLabel('9月26日 周六');
  await wait('document.body.innerText.includes("手阻抬头练习")', 'selected day exercises still available');
  assert.ok(!(await evaluate('document.body.innerText')).includes('2026年9月26日 · 周六'), 'redundant date header removed');
  await screenshot('today-simplified-mobile.png');
  await clickLabel('查看倒立训练条件');
  await wait('document.body.innerText.includes("轻量手阻抬头")', 'gate detail remains available');
  await screenshot('today-gate-details-mobile.png');
  await click('关闭');
  await click('开始今日训练  →');
