  await click('删除这条记录'); await click('删除记录');
  await wait('JSON.parse(localStorage.getItem("sessions")).length === 1', 'delete persisted');
  await click('今日');
  await wait('document.body.innerText.includes("尚未解锁")', 'delete relocks');
  console.log('PASS delete record refreshes day state and unlock');
  await click('＋ 添加动作');
  await wait('!!document.querySelector("input[placeholder=搜索动作名称]")', 'exercise picker');
  await fillLabel('搜索训练动作', '标准俯卧撑');
  await clickLabel('添加标准俯卧撑');
  await wait('Object.values(JSON.parse(localStorage.getItem("daily_workout_edits"))).some(e=>e.exerciseIds.includes("push_05"))', 'daily edit persisted');
  await click('开始今日训练  →');
  await wait('document.body.innerText.includes("2. 标准俯卧撑")', 'extra action in active course');
  await clickLabel('第1组完成'); await clickLabel('保存并退出训练'); await click('保存并退出');
  await wait('JSON.parse(localStorage.getItem("sessions")).length === 2', 'second partial');
  await click('重置今天'); await click('重置今天');
  await wait('JSON.parse(localStorage.getItem("sessions")).length === 1 && Object.keys(JSON.parse(localStorage.getItem("daily_workout_edits"))).length === 0', 'reset persisted');
  assert.equal((await evaluate('JSON.parse(localStorage.getItem("sessions"))[0]')).id, historical.id);
  await click('开始今日训练  →'); await wait('document.body.innerText.includes("训练计时")', 'rerun after reset');
  assert.equal(await evaluate('document.querySelectorAll("[role=checkbox][aria-checked=true]").length'), 0);
  await screenshot('training-main-mobile.png');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 320, height: 640, deviceScaleFactor: 1, mobile: true });
  await click('手动开始休息');
  await screenshot('training-rest-small.png');
  assert.ok(await evaluate('document.documentElement.scrollWidth <= 320'), 'no horizontal overflow on a narrow phone');
  await click('结束休息');
  await cdp('Emulation.setDeviceMetricsOverride', { width: 1200, height: 900, deviceScaleFactor: 1, mobile: false });
  await screenshot('training-desktop.png');
  await clickLabel('查看今日热身动作');
  await wait('document.body.innerText.includes("热身第 1 组")', 'specific warmup actions');
  await new Promise((resolve) => setTimeout(resolve, 500));
  await screenshot('training-warmup.png');
  await click('已完成热身');
  await clickLabel('保存并退出训练'); await click('退出');
  await wait('document.body.innerText.includes("开始今日训练")', 'empty exit');
  assert.equal(await evaluate('JSON.parse(localStorage.getItem("sessions")).length'), 1);
  console.log('PASS custom daily action, reset removes only today, rerun clean, no empty record');
  await click('开始今日训练  →');
  await wait('document.body.innerText.includes("训练计时")', 'complete course');
  for (let set = 1; set <= 3; set++) await clickLabel('第' + set + '组完成');
  await click('保存训练');
  await clickLabel('按动作稳定保存训练');
  await wait('document.body.innerText.includes("今天的训练已完成")', 'complete saved');
  assert.ok(await evaluate('Array.from(document.querySelectorAll(\'[role="button"],[tabindex="0"],button\')).some(e => e.textContent.trim() === "再练一次")'), 'rerun button uses the concise label');
  assert.ok(!(await evaluate('document.body.innerText')).includes('保留原记录'));
  assert.equal(await evaluate('JSON.parse(localStorage.getItem("sessions"))[0].completion'), 'complete');
  assert.equal(await evaluate('JSON.parse(localStorage.getItem("sessions"))[0].quality'), 'solid');
  await click('重置今天'); await click('重置今天');
  await wait('JSON.parse(localStorage.getItem("sessions")).length === 1', 'reset complete record');
  console.log('PASS explicit finish replaces draft without duplication');
  await click('开始今日训练  →');
  await wait('document.body.innerText.includes("训练计时")', 'autosave exercise');
