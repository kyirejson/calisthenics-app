  await clickLabel('保存并退出训练'); await click('保存并退出');
  await wait('JSON.parse(localStorage.getItem("sessions")).length === 2 && document.body.innerText.includes("已满足解锁条件")', 'partial save and unlock');
  const saved = await evaluate('JSON.parse(localStorage.getItem("sessions"))[0]');
