const { readFeature } = require('./lib/project-features.cjs');
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
test('today removes rejected clutter and keeps the compact plan entry', () => {
  const today = readFeature('today');
  assert.ok(!/TrainingGoalSelector|TrainingGoalPicker|streakDays|heroProgress|heroExpand|planSettingsCard/.test(today));
  assert.ok(today.includes('style={styles.frequencyTrigger}'));
  assert.ok(today.includes('TrainingStagePicker'));
  assert.ok(read('src/screens/ProfileScreen.tsx').includes('title="训练专题"'));
  assert.ok(!read('src/screens/EquipmentTodayScreen.tsx').includes('TrainingGoalSelector'));
});
test('stage options are accessible and never mutate a profile before applying', () => {
  const picker = read('src/components/TrainingStagePicker.tsx');
  assert.equal((picker.match(/key: '(beginner|intermediate|advanced|elite|supermax)'/g) || []).length, 5);
  assert.ok(picker.includes('accessibilityRole="radio"'));
  assert.ok(!/patchProfile|switchTrainingGoal/.test(picker));
  assert.ok(readFeature('today').includes('setShowPlanPreview(false)'));
});
test('today template orders date rail, phase controls, editorial course, task cards and fixed start', () => {
  const today = readFeature('today');
  const start = today.indexOf('<View style={styles.trainingRoot}');
  const dates = today.indexOf('testID="today-date-rail"', start);
  const schedule = today.indexOf('testID="today-schedule-controls"', start);
  const course = today.indexOf('testID="today-course-card"', start);
  const actions = today.indexOf('testID="today-workout-list"', start);
  const pageEnd = today.indexOf('</Page>', actions);
  const dock = today.indexOf('testID="today-start-dock"', start);
  assert.ok(start < dates && dates < schedule && schedule < course && course < actions && actions < pageEnd && pageEnd < dock);
  const task = read('src/components/TodayTrainingTask.tsx');
  assert.ok(task.includes('String(index + 1).padStart(2'));
  assert.ok(task.includes('Math.max(exercise.targetSets, completedSets.length)'));
  assert.ok(task.includes('exercise.targetValue'));
  assert.ok(task.includes('exercise.targetUnit'));
  assert.ok(task.includes('exercise.restSeconds'));
  assert.ok(task.includes('exercise.perSide'));
  assert.ok(task.includes('today-completed-'));
  assert.ok(!task.includes('useAppStore'), 'presentation receives completion instead of owning storage');
  assert.ok(today.includes('testID="today-selected-day-notes"'));
  assert.ok(!/ScheduleDayDetail|dayDetailOpen|today-schedule-sheet/.test(today));
  assert.ok(!/chevron|AppGlyph/.test(task));
  assert.ok(today.includes('getTrainingDayView(profile, sessions, dailyEdits, now, viewDate)'));
  assert.match(today, /onViewDateChange\(null\);\s*return;/);
  assert.ok(read('App.tsx').includes('viewDate={todayViewDate}'));
  for (const dead of ['scheduleTop', 'pageScroll', 'styles.heroIntro', 'styles.heroAction', 'styles.dupTag', 'styles.scheduleDetailWrap', 'roomyExerciseName', 'heroExerciseRow']) assert.ok(!today.includes(dead));
  assert.ok(today.includes('workoutExercises.map((exercise, index)'));
  assert.ok(!today.includes('workoutExercises.slice('));
});
test('cockpit primary and rest controls stay outside scrolling content', () => {
  const screen = read('src/components/TrainingCockpit.tsx');
  const scrollStart = screen.indexOf('<ScrollView testID="training-scroll"');
  const dock = screen.indexOf('<View style={s.footer}>');
  assert.ok(dock > scrollStart && screen.lastIndexOf('</ScrollView>', dock) > scrollStart);
  assert.ok(!screen.includes("accessibilityRole=\"checkbox\""));
  assert.ok(screen.includes('撤销第'));
  assert.ok(screen.includes('keyboardShouldPersistTaps="handled"'));
  assert.ok(screen.includes('KeyboardAvoidingView'));
  assert.ok(screen.includes('实际'));
  assert.ok(!screen.includes('tableHeader'));
  assert.ok(readFeature('training').includes('useHideAgentDock()'));
  assert.doesNotMatch(screen, /onChat|name="chat"|打开 MAX 聊天/);
  assert.doesNotMatch(readFeature('training'), /useOpenAgentChat|openChat|onChat=/);
});
test('finishing training saves without a subjective feedback modal or invented quality', () => {
  const dialogs = read('src/features/training/TrainingDialogs.tsx');
  const session = read('src/features/training/useTrainingSession.ts');
  assert.doesNotMatch(dialogs, /训练感觉如何|qualityOption|showQuality|按动作稳定/);
  assert.doesNotMatch(session, /setShowQuality|SessionQuality|quality:\s*'solid'/);
  assert.match(session, /else void save\(\)/);
  assert.match(session, /saveSession\(createRecord\(true, leave\)\)/);
  assert.match(session, /保存失败，已完成内容仍在本页，请重试/);
});
